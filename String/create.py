'''
Escape characters
Escape characters begin with a backslash (\).
Escape	Meaning	        Example
\n	    New line	    "Hello\nWorld"
\t	    Tab	            "Hello\tWorld"
\\	    Backslash	    "C:\\Users"
\'	    Single quote	'It\'s Python'
\"	    Double quote	"Say \"Hi\""
'''
print("Hello\nWorld")
print("Name:\tAkash")