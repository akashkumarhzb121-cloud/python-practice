#3. The if statement
'''
The if statement executes a block only when its condition is true.
Syntax:
if condition:
Code executes if condition is True
'''
age = 20

if age >= 18:
    print("You are eligible to vote.")

#Python uses indentation to define the body of a control statement.
age = 30

if age >= 18:
    print("Adult")  # Inside the if block

print("Program finished")  # Outside the if block