#1. What is an operator?
a = 10
b = 5

print(a + b)

'''
An operator is a symbol or keyword that performs an operation on one or more values.
Here:
- a and b are operands — the values being operated on.
- + is the operator — it performs addition.
- a + b is an expression.
- print() displays the result.
Python operators are commonly grouped into these categories:
1. Arithmetic operators
2. Assignment operators
3. Comparison (relational) operators
4. Logical operators
5. Bitwise operators
6. Membership operators
7. Identity operators
'''