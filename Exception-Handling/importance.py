#2. Why is exception handling important?
'''
Imagine you create a student management system. A user accidentally enters text instead of marks, or the application cannot find a file.

Without exception handling, an unhandled exception may terminate the current operation. With appropriate handling, you can display a useful message and allow the program to continue where it is safe to do so.

Exception handling helps you:
- Prevent common runtime errors from crashing the whole workflow.
- Give users understandable error messages.
- Handle invalid input.
- Deal with missing files and unavailable resources.
- Separate normal program logic from error-handling logic.
Important: exception handling does not make incorrect operations magically succeed. It allows you to respond to failures appropriately.
'''